/**
 * Validates tooling/ux/feature-surface-map.mjs against the plan catalog and
 * emits the PHASE 0A report.
 *
 *   node tooling/ux/verify-feature-surface-map.mjs           # validate + summary
 *   node tooling/ux/verify-feature-surface-map.mjs --md      # full markdown report
 *
 * Exits non-zero on any coverage or consistency failure, so it can be wired
 * into CI the same way the other repository validators are.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { MAP, TYPES, SURFACES, LEVELS } from "./feature-surface-map.mjs";

// Bumped by hand when someone re-checks this report against the map and the
// catalogue. Deliberately not `new Date()`: a date that moves on every run says
// only that the generator ran, which is the one thing nobody needs to be told,
// and it would make the CI staleness diff fail on any day the file was
// regenerated.
const LAST_VERIFIED = "2026-09-05";

const here = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(here, "..", "..");
const catalog = JSON.parse(
  readFileSync(resolve(workspace, "docs/product/orderak-plan-catalog.json"), "utf8"),
);

const features = catalog.features;
const byKey = new Map(features.map(f => [f.key, f]));
const errors = [];

/* ---------- coverage ---------- */
for (const f of features) {
  if (!(f.key in MAP)) errors.push(`missing classification: ${f.key}`);
}
for (const key of Object.keys(MAP)) {
  if (!byKey.has(key)) errors.push(`classified key not in catalog: ${key}`);
}

/* ---------- consistency ---------- */
for (const [key, entry] of Object.entries(MAP)) {
  if (!Array.isArray(entry) || entry.length !== 3) {
    errors.push(`${key}: entry must be [type, surface, level]`);
    continue;
  }
  const [type, surface, level] = entry;
  if (!TYPES.includes(type)) errors.push(`${key}: unknown type "${type}"`);
  if (!LEVELS.includes(level)) errors.push(`${key}: unknown level "${level}"`);
  if (type === "NONE") {
    if (surface !== "—") errors.push(`${key}: NONE must carry surface "—", got "${surface}"`);
  } else if (!SURFACES.includes(surface)) {
    errors.push(`${key}: unknown surface "${surface}"`);
  }
  // An implemented feature cannot be parked in the far future.
  const f = byKey.get(key);
  if (f && f.implementation_status === "implemented" && level === "L4") {
    errors.push(`${key}: implemented but classified L4`);
  }
}

if (errors.length) {
  console.error(`FAIL — ${errors.length} problem(s):`);
  for (const e of errors) console.error("  " + e);
  process.exit(1);
}

/* ---------- aggregate ---------- */
const count = (pred) => features.filter(pred).length;
const t = k => MAP[k][0], s = k => MAP[k][1], l = k => MAP[k][2];

const byType = Object.fromEntries(TYPES.map(x => [x, count(f => t(f.key) === x)]));
const byLevel = Object.fromEntries(LEVELS.map(x => [x, count(f => l(f.key) === x)]));

const surfaceRows = SURFACES.map(surface => {
  const fs = features.filter(f => s(f.key) === surface);
  return {
    surface,
    total: fs.length,
    screens: fs.filter(f => t(f.key) === "SCREEN").length,
    sections: fs.filter(f => t(f.key) === "SECTION").length,
    fields: fs.filter(f => t(f.key) === "FIELD").length,
    l1: fs.filter(f => l(f.key) === "L1").length,
    built: fs.filter(f => f.implementation_status === "implemented").length,
  };
});

/* ---------- output ---------- */
if (!process.argv.includes("--md")) {
  console.log(`OK — all ${features.length} catalog features classified.\n`);
  console.log("BY TYPE");
  for (const [k, v] of Object.entries(byType)) console.log(`  ${k.padEnd(8)} ${String(v).padStart(3)}`);
  console.log("\nBY LEVEL");
  for (const [k, v] of Object.entries(byLevel)) console.log(`  ${k.padEnd(8)} ${String(v).padStart(3)}`);
  console.log("\nBY SURFACE                total  screens  sections  fields   L1  built");
  for (const r of surfaceRows) {
    console.log(
      `  ${r.surface.padEnd(22)} ${String(r.total).padStart(5)} ${String(r.screens).padStart(8)} ` +
      `${String(r.sections).padStart(9)} ${String(r.fields).padStart(7)} ${String(r.l1).padStart(4)} ${String(r.built).padStart(6)}`,
    );
  }
  const none = features.filter(f => t(f.key) === "NONE").length;
  console.log(`  ${"(no UI)".padEnd(22)} ${String(none).padStart(5)}`);

  console.log(`\nNEW SCREENS TO DESIGN: ${count(f => t(f.key) === "SCREEN" && f.implementation_status === "planned")}`);
  console.log(`L1 features total:     ${byLevel.L1}`);
  process.exit(0);
}

/* markdown report */
const out = [];
out.push("---");
out.push("status: current");
out.push("generated: true");
out.push("owner: product");
out.push(`last_verified: ${LAST_VERIFIED}`);
out.push("applies_to: [internal]");
out.push("---");
out.push("# Feature → surface map");
out.push("");
out.push("Generated by `tooling/ux/verify-feature-surface-map.mjs --md` from");
out.push("`tooling/ux/feature-surface-map.mjs`. Do not edit by hand — change the map.");
out.push("");
out.push(`All **${features.length}** catalog features are classified. This is what proves the`);
out.push("five surfaces can hold the whole product.");
out.push("");
out.push("| Type | Count | Meaning |");
out.push("| --- | --- | --- |");
out.push(`| \`SCREEN\` | ${byType.SCREEN} | full screen with its own route |`);
out.push(`| \`SECTION\` | ${byType.SECTION} | block inside an existing screen |`);
out.push(`| \`FIELD\` | ${byType.FIELD} | single input, toggle or column |`);
out.push(`| \`NONE\` | ${byType.NONE} | backend or storefront only |`);
out.push("");
out.push("## Load per surface");
out.push("");
out.push("| Surface | Features | Screens | Sections | Fields | L1 | Built today |");
out.push("| --- | --- | --- | --- | --- | --- | --- |");
for (const r of surfaceRows) {
  out.push(`| ${r.surface} | ${r.total} | ${r.screens} | ${r.sections} | ${r.fields} | ${r.l1} | ${r.built} |`);
}
out.push("");
out.push("## Experience levels");
out.push("");
out.push("| Level | Count |");
out.push("| --- | --- |");
for (const lv of LEVELS) out.push(`| ${lv} | ${byLevel[lv]} |`);
out.push("");

/* ---------- architecture verdict ---------- */
const near = SURFACES.map(surface => ({
  surface,
  near: features.filter(f => s(f.key) === surface && t(f.key) === "SCREEN" && l(f.key) !== "L4").length,
  far: features.filter(f => s(f.key) === surface && t(f.key) === "SCREEN" && l(f.key) === "L4").length,
}));
out.push("## Architecture verdict");
out.push("");
out.push("Screen count per surface, split by how far out the feature is. The near");
out.push("column is what the architecture has to carry in practice; the far column is");
out.push("what it has to have room for.");
out.push("");
out.push("| Surface | Screens L1–L3 | Screens L4 | Total |");
out.push("| --- | --- | --- | --- |");
for (const r of near) out.push(`| ${r.surface} | ${r.near} | ${r.far} | ${r.near + r.far} |`);
out.push("");
const acct = near.find(r => r.surface === "account");
out.push(`**The five surfaces hold.** Near-term load is ${near.map(r => r.near).join(" / ")}`);
out.push("(today / orders / store / customers / account) — comparable, with `store` the");
out.push("busiest and therefore the right first surface to rebuild.");
out.push("");
out.push(`**The one real risk is \`account\` at L4**: ${acct.far} of its ${acct.near + acct.far} screens are L4, and`);
out.push("they cluster into one coherent group — team, roles, permissions, SSO, IP");
out.push("restrictions, API keys, webhooks, automation, audit. That is organisation");
out.push("administration, not \"my account\".");
out.push("");
out.push("**Documented seam, not built now:** when an organisation actually has teams and");
out.push("API access, `account` splits into `حسابي` (identity, store, plan, support) and");
out.push("an organisation-administration surface. Naming the seam now is what stops");
out.push("`account` becoming the settings dumping ground the migration exists to remove.");
out.push("Until then `account` keeps its four groups and no L4 screen is built.");
out.push("");
for (const surface of SURFACES) {
  out.push(`## Surface: ${surface}`);
  out.push("");
  out.push("| Key | Type | Level | Status |");
  out.push("| --- | --- | --- | --- |");
  for (const f of features.filter(x => s(x.key) === surface)) {
    out.push(`| \`${f.key}\` | ${t(f.key)} | ${l(f.key)} | ${f.implementation_status} |`);
  }
  out.push("");
}
out.push("## No seller-facing UI");
out.push("");
out.push("| Key | Level | Status |");
out.push("| --- | --- | --- |");
for (const f of features.filter(x => t(x.key) === "NONE")) {
  out.push(`| \`${f.key}\` | ${l(f.key)} | ${f.implementation_status} |`);
}
out.push("");
// Trailing empties plus console.log's own newline give a double blank line at
// end of file, which markdownlint MD012 rejects.
while (out.length && out[out.length - 1] === "") out.pop();
console.log(out.join("\n"));
