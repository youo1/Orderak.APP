#!/usr/bin/env node
// ============================================================
// Writes `docs/admin/information-architecture.md` from the panel's own registry.
//
// G4 asks for three things and this is the second one: "the panel's information
// architecture is documented as a tree with a stated purpose per branch, and no
// branch exists solely because a table does."
//
// The tree is generated rather than written so it cannot describe a panel that
// does not exist. `verify-admin-ia.mjs` holds the registry it reads to the shell
// and the contract, so the chain is: the guard proves the two registries agree,
// and this document is a rendering of what they agree on.
//
// Usage: node tooling/ux/document-admin-ia.mjs
// ============================================================

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const appSectionsPath = path.join(repositoryRoot, "apps", "admin-web", "src", "app", "config", "sections.ts");
const outPath = path.join(repositoryRoot, "docs", "admin", "information-architecture.md");

const appSource = readFileSync(appSectionsPath, "utf8");
const sections = [
	...appSource.matchAll(
		/\{ id: '([^']+)', path: '([^']+)', label: '([^']+)', description: '([^']*)', group: '([^']+)', permission: '([^']+)'/g,
	),
].map((m) => ({ id: m[1], path: m[2], label: m[3], description: m[4], group: m[5], permission: m[6] }));

if (sections.length === 0) {
	console.error("document-admin-ia: parsed no sections — the registry's shape changed.");
	process.exit(1);
}

/**
 * What each branch is for, in an operator's terms.
 *
 * The registry's `description` says what a section holds. This says what job it
 * serves and what it is not — the half of G4's last clause that a machine cannot
 * check, because "this branch exists because a queue is a table" reads perfectly
 * well until someone asks who the branch is for.
 */
const BRANCH_PURPOSE = {
	Overview: "One screen for the question an operator opens the panel with: is anything wrong right now. It is the landing view, so G4's depth budget starts here.",
	Accounts: "Everything about one seller, one buyer or one support thread. Grouped by who is involved rather than by which table the record lives in — a seller's devices, subscription and trust state are one operator job, not three.",
	Commerce: "Money in: what is sold, what was paid, what is owed and what was refunded. Split by the decision an operator makes, so a verification queue and a plan catalogue are separate sections even though both read subscription rows.",
	Governance: "The switches that change what the platform does — flags, version gates, capability state, runtime configuration. Every section here is a control an operator can move, and each states its scope.",
	Communication: "What the platform says to sellers and buyers — announcements, translations, transactional email, inbound replies and the macros support uses. The content sections are here because an operator's job is to change the words, not to read a template table.",
	"Engineering": "The panel looking at itself: manifests, prompts, design assets, endpoint inventory. Operator-facing because keeping them current IS the job, and each section names the artefact it maintains rather than the file it reads.",
	System: "Access, audit and health for the people using the panel. An operator is here to answer 'who did this' and 'what is broken', so those are the two organising ideas.",
};

const groups = [...new Set(sections.map((s) => s.group))];

const out = [];
out.push("---");
out.push("status: current");
out.push("generated: true");
out.push("owner: backend");
out.push("applies_to: [internal]");
out.push("---");
out.push("# Admin control plane — information architecture");
out.push("");
out.push("Generated by `tooling/ux/document-admin-ia.mjs` from");
out.push("`apps/admin-web/src/app/config/sections.ts`. Do not edit by hand — change the");
out.push("registry. `tooling/ux/verify-admin-ia.mjs` keeps that registry and");
out.push("`contracts/typescript/admin.ts` in agreement, and fails the build if the depth");
out.push("claim below stops being true.");
out.push("");
out.push(`**${sections.length} sections in ${groups.length} groups.** Every one is reachable in`);
out.push("**one navigation** from the landing view: the sidebar renders each group as a");
out.push("heading over flat links, so nothing is behind a menu. G4 allows two; the");
out.push("registry's own shape is what makes it one.");
out.push("");
out.push("| Group | Sections | Reach |");
out.push("| --- | --- | --- |");
for (const group of groups) {
	out.push(`| ${group} | ${sections.filter((s) => s.group === group).length} | 1 navigation |`);
}
out.push("");
out.push("## What each branch is for");
out.push("");
out.push("G4's last clause is that no branch exists solely because a table does. A branch");
out.push("is justified by the operator job it serves, not by the rows it reads, so each");
out.push("group below states its job and the tree under it names what an operator does");
out.push("there.");
out.push("");

for (const group of groups) {
	out.push(`### ${group}`);
	out.push("");
	out.push(BRANCH_PURPOSE[group] ?? "*(no purpose recorded — add one to `BRANCH_PURPOSE` in the generator)*");
	out.push("");
	out.push("| Section | Path | Permission | What an operator does |");
	out.push("| --- | --- | --- | --- |");
	for (const section of sections.filter((s) => s.group === group)) {
		out.push(`| ${section.label} | \`${section.path}\` | \`${section.permission}\` | ${section.description} |`);
	}
	out.push("");
}

out.push("## Depth, measured");
out.push("");
out.push("The claim above is not an assertion about intent. `verify-admin-ia.mjs` reads the");
out.push("shell's `<nav>` and fails when it stops being a flat list of links, because a");
out.push("collapsible group would move its sections to two navigations and the sentence");
out.push("above would become false in a file nobody re-reads.");
out.push("");
out.push("## Changing this");
out.push("");
out.push("Add or move a section in `apps/admin-web/src/app/config/sections.ts`, then mirror");
out.push("the identity in `contracts/typescript/admin.ts`. Labels are deliberately not");
out.push("compared between the two: the shell owns the words an operator reads, and a");
out.push("sidebar label is shortened to fit the rail.");
out.push("");
while (out.length && out[out.length - 1] === "") out.pop();
out.push("");

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, out.join("\n"), "utf8");
console.log(`Wrote ${path.relative(repositoryRoot, outPath).replace(/\\/g, "/")}: ${sections.length} sections in ${groups.length} groups.`);
